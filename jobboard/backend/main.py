"""jobboard backend — one shared document per portal project.

Generated by scripts/new-rack-service.mjs from src-lilak/def.js. The keys are
the declaration's (the items, each class with fields of its own, settings);
re-run with --sync after changing them there rather than editing this.
By hand since: the flow board tab's keys (evaluations, approval, prefs, pins),
where each person is looking, /api/focus (flow_api.py), approvals (approval_api.py), and one job's log,
files and recipe from its jobrun (jobrun_api.py), and a job's change history
(history_api.py).

The document is stored whole and versioned; a save edited from an older version
is refused with 409. Every save keeps what it replaces (keep_days).
"""
import os
from pathlib import Path

from fastapi import FastAPI

import approval_api
import flow_api
import history_api
import jobrun_api
import pull_stark
from rackstore.store import Document, mount_spa

DATA = Path(os.environ.get("JOBBOARD_DATA_DIR", "./data"))
PROJECT = os.environ.get("PORTAL_PROJECT", "")
DIST = Path(os.environ.get("JOBBOARD_DIST_DIR", "./dist"))

DOC = Document(DATA / "data.json", keys=("jobs", "evaluations", "approval", "prefs", "pins", "settings"), keep_days=30)

app = FastAPI(title="jobboard")
DOC.mount(app, project=PROJECT)
pull_stark.start(DOC)
flow_api.mount(app, DATA)
jobrun_api.mount(app, DOC)
history_api.mount(app, DOC)
approval_api.mount(app, DOC)

# Must stay last: the catch-all would shadow /api/*.
mount_spa(app, DIST, name="jobboard")
